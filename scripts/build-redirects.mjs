// Writes dist/_redirects from redirects/legacy-wordpress.csv after `astro build`.
//
// The CSV is the map from old WordPress URLs to pages on this site. It opens in
// any spreadsheet: edit a row, commit, and the next deploy picks it up.
//
// Two checks fail the build rather than ship a bad map:
//   - a redirect whose target page does not exist in dist/ (a guide was
//     renamed or deleted, and its redirects would now land on a 404)
//   - a redirect whose source is a live page (it would shadow the real page)
//
// Old URLs that are not in the CSV fall through to the 404 page, which is the
// right answer for off-topic posts and thin auto-generated pages.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const DIST = 'dist';
const CSV = 'redirects/legacy-wordpress.csv';

// Whole WordPress sections, matched after the per-URL rows. Netlify takes the
// first matching rule, so the specific rows above always win.
const PATTERNS = [
  ['/category/*', '/guides'],
  ['/tag/*', '/guides'],
  ['/blog/*', '/guides'],
  ['/shawn-ryder-digital-blog/*', '/guides'],
  ['/author/*', '/about'],
  ['/automation/*', '/services'],
  ['/engage-customers/*', '/guides'],
  ['/feed', '/rss.xml'],
  ['/feed/*', '/rss.xml'],
  ['/comments/feed', '/rss.xml'],
];

/** Minimal CSV reader: handles quoted fields with commas, which the reason column uses. */
function parseCsv(text) {
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const cells = [];
    let cur = '';
    let quoted = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (quoted) {
        if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; }
        else if (c === '"') quoted = false;
        else cur += c;
      } else if (c === '"') quoted = true;
      else if (c === ',') { cells.push(cur); cur = ''; }
      else cur += c;
    }
    cells.push(cur);
    rows.push(cells);
  }
  return rows;
}

const pageExists = (path) => {
  if (path === '/') return existsSync(join(DIST, 'index.html'));
  const clean = path.replace(/\/+$/, '');
  return existsSync(join(DIST, `${clean}.html`)) || existsSync(join(DIST, clean, 'index.html')) || existsSync(join(DIST, clean));
};

const [header, ...rows] = parseCsv(readFileSync(CSV, 'utf8'));
const col = Object.fromEntries(header.map((h, i) => [h.trim(), i]));
const problems = [];
const seen = new Set();
const lines = [
  '# Generated by scripts/build-redirects.mjs from redirects/legacy-wordpress.csv.',
  '# Edit the CSV, not this file.',
];

for (const row of rows) {
  const from = '/' + row[col.from].trim().replace(/^\/+|\/+$/g, '');
  const to = row[col.to].trim();
  if (!from || from === '/' || !to) continue;
  if (seen.has(from)) { problems.push(`duplicate source ${from}`); continue; }
  seen.add(from);
  if (pageExists(from)) problems.push(`${from} is a live page — redirecting it would hide it`);
  if (!pageExists(to)) problems.push(`${from} → ${to}: target page does not exist`);
  lines.push(`${from}  ${to}  301`);
}

for (const [from, to] of PATTERNS) {
  if (!pageExists(to)) problems.push(`pattern ${from} → ${to}: target page does not exist`);
  lines.push(`${from}  ${to}  301`);
}

if (problems.length) {
  console.error(`\nRedirect map has ${problems.length} problem(s):\n  ${problems.join('\n  ')}\n`);
  process.exit(1);
}

writeFileSync(join(DIST, '_redirects'), lines.join('\n') + '\n');
console.log(`_redirects: ${seen.size} legacy URLs + ${PATTERNS.length} section patterns`);
